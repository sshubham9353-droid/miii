export function generateFeeRecords(students: Student[]): FeeRecord[] {
  return students.map((s) => {
    const outstanding = s.monthlyFee - s.paidAmount;
    let status: FeeRecord['status'];
    if (outstanding <= 0) status = 'Paid';
    else if (s.paidAmount > 0) status = 'Partially Paid';
    else {
      const due = new Date(s.feeDueDate);
      const now = new Date('2024-10-09');
      status = due < now ? 'Overdue' : 'Pending';
    }
    return {
      id: `fee-${s.id}`,
      studentId: s.id,
      studentName: s.name,
      rollNumber: s.rollNumber,
      seatNumber: s.seatNumber,
      monthlyFee: s.monthlyFee,
      amountPaid: s.paidAmount,
      outstandingBalance: Math.max(outstanding, 0),
      dueDate: s.feeDueDate,
      status,
    };
  });
}
