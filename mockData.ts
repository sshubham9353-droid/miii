function generateInitialSeats(total: number, students: Student[]): Seat[] {
  const seats: Seat[] = [];
  for (let i = 1; i <= total; i++) {
    const assigned = students.find((s) => s.seatNumber === i);
    seats.push({
      id: `seat-${i}`,
      seatNumber: i,
      status: assigned ? 'Occupied' : i === 11 ? 'Reserved' : i === 12 ? 'Maintenance' : 'Available',
      assignedStudentId: assigned ? assigned.id : null,
      assignedStudentName: assigned ? assigned.name : null,
      assignedStudentRoll: assigned ? assigned.rollNumber : null,
    });
  }
  return seats;
}

